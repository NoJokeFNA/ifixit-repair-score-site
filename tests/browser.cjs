const {site, json, assert} = require('./helpers.cjs');
(async () => {
  const devices = json('devices_with_scores.json');
  await site(async page => {
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await page.locator('#stat-all').innerText(), new Intl.NumberFormat('en-GB').format(devices.length));
    await page.locator('#page-size').selectOption('25');
    const scored = devices.filter(d => typeof d.repairability_score === 'number');
    assert.equal(await page.locator('#device-rows tr').count(), Math.min(25, scored.length));
    await page.reload();
    await page.waitForFunction(() => /^\d/.test(document.querySelector('#result-count').textContent));
    assert.equal(await page.locator('#page-size').inputValue(), '25');
    await page.locator('#brand').selectOption('Fairphone');
    const expected = scored.filter(d => d.brand === 'Fairphone');
    assert.equal(Number((await page.locator('#result-count').innerText()).replaceAll(',', '')), expected.length);
    await page.locator('.device-name').first().click();
    await page.locator('#detail-dialog').waitFor({state: 'visible'});
    assert.ok(await page.locator('#detail-content a[href^="https://www.ifixit.com/"]').count());
    await page.keyboard.press('Escape');
    await page.locator('#reset').click();
    await page.locator('.row-select').first().check();
    await page.locator('.row-select').nth(1).check();
    await page.locator('#open-comparison').click();
    assert.equal(await page.locator('.compare-card').count(), 2);
    await page.locator('[data-remove]').first().click();
    assert.equal(await page.locator('.compare-card').count(), 1);
    await page.locator('.footer-about').click();
    assert.ok(await page.locator('#about-view').isVisible());
    assert.equal(await page.locator('#about-view a[href*="xiongchiamiov"]').count(), 1);
    assert.equal(await page.locator('a[href="https://github.com/NoJokeFNA/ifixit-repair-score-site"]').count(), 1);
  });
  console.log('Explorer, saved page size, device details, comparison and project credits passed');
})().catch(error => {console.error(error); process.exit(1);});
