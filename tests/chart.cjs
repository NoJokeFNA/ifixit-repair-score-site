const {site, device, assert} = require('./helpers.cjs');
(async () => {
  const rows = [device('Zero Phone',0),device('Four Phone',4),device('Ten Phone',10),device('Unscored Phone',null)];
  await site(async page => {
    assert.equal(await page.locator('#device-rows tr').count(),3);
    assert.ok((await page.locator('[data-score="0"]').getAttribute('aria-label')).includes('1 devices'));
    await page.locator('[data-score="0"]').click();
    assert.equal(await page.locator('.device-name').innerText(),'Zero Phone');
    await page.locator('[data-score="0"]').click();
    assert.equal(await page.locator('#device-rows tr').count(),3);
    await page.locator('#search').fill('Four');
    await page.locator('[data-score="4"]').click();
    assert.equal(await page.locator('.device-name').innerText(),'Four Phone');
    await page.locator('#chart-reset').click();
    assert.equal(await page.locator('#search').inputValue(),'Four');
    await page.locator('#reset').click();
    await page.locator('[data-scope="all"]').click();
    assert.equal(await page.locator('#device-rows tr').count(),4);
  },{overrides:{'devices_with_scores.json':rows,'images.json':{}}});
  const reported=(score)=>({status:'matched',score,sources:[{name:'Verified variant',score,url:'https://www.indicereparabilite.fr/produit/example/'}]});
  const frenchRows=[device('French A',0,reported(9.2)),device('French B',4,reported(9.3)),device('French C',10,reported(10)),device('French only',null,reported(6))];
  await site(async page=>{
    await page.locator('[data-chart-system="french"]').click();
    assert.equal(await page.locator('#result-count').innerText(),'4');
    assert.equal(await page.locator('#chart-title').innerText(),'FRENCH INDEX DISTRIBUTION');
    assert.equal(await page.locator('#histogram .bar-button').count(),10);
    assert.ok((await page.locator('[data-score="9"]').getAttribute('aria-label')).includes('3 devices'));
    await page.locator('[data-score="9"]').click();
    assert.equal(await page.locator('#device-rows tr').count(),3);
    await page.locator('#chart-reset').click();
    const row=page.locator('#device-rows tr').filter({hasText:'French C'});
    assert.equal(await row.locator('.score-badge').count(),2);
    assert.equal(await row.locator('.mini-track').count(),2);
    await page.locator('[data-score="6"]').click();
    assert.equal(await page.locator('.device-name').innerText(),'French only');
    await page.locator('[data-chart-system="ifixit"]').click();
    assert.equal(await page.locator('#device-rows tr').count(),3);
    assert.equal(await page.locator('#histogram .bar-button').count(),11);
  },{overrides:{'devices_with_scores.json':frenchRows,'images.json':{}}});
  console.log('Score zero, chart counts, filter cancellation and independent search passed');
})().catch(error=>{console.error(error);process.exit(1);});
